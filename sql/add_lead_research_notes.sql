-- v7.10.16 — Research Notes and General Notes on leads (Richard 2026-10-24, the email to Les:
-- "I am removing all Details and Notes from the Leads Section … a form, named Research Notes, that
-- becomes available only when the origin of the lead is Research … a second notes section called
-- General Notes … no restrictions and do not have to be completed").
--   leads.general_notes            free text on every lead, optional
--   lead_research_interviews       Les's research interview record, up to three per lead (1/3 · 2/3 · 3/3)
-- Additive, re-runnable, SQL-editor safe (no psql meta-commands). Run on BOTH databases, before or
-- with the code (the form says what is missing until it has run).
BEGIN;

ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS general_notes TEXT;

CREATE TABLE IF NOT EXISTS public.lead_research_interviews (
  id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id                  BIGINT NOT NULL REFERENCES public.leads(id) ON DELETE CASCADE,
  interview_no             SMALLINT NOT NULL DEFAULT 1 CHECK (interview_no BETWEEN 1 AND 3),
  interview_date           DATE,
  interviewer_id           BIGINT REFERENCES public.people(id) ON DELETE SET NULL,
  participant              TEXT,          -- name and research identifier
  role                     TEXT,          -- job title
  organisation             TEXT,          -- company name
  target_market            TEXT,          -- Xone target market
  target_segment           TEXT,          -- target market segment
  anonymity                TEXT CHECK (anonymity IS NULL OR anonymity IN ('full', 'partial', 'quote_me')),
  guard_headcount          TEXT,
  guard_headcount_estimate TEXT,          -- if not disclosed, estimated from other sources
  guarding_spend           TEXT,
  control_room_spend       TEXT,
  spend_estimate           TEXT,          -- if not disclosed, estimated from other sources
  technology_notes         TEXT,
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by               BIGINT REFERENCES public.people(id) ON DELETE SET NULL,
  updated_at               TIMESTAMPTZ,
  updated_by               BIGINT REFERENCES public.people(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_lead_research_interviews_lead ON public.lead_research_interviews (lead_id);

ALTER TABLE public.lead_research_interviews ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.lead_research_interviews TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.lead_research_interviews_id_seq TO service_role;

-- Statement-level audit, like the other business tables (audit_stmt from sql/perf_tier1_audit_statement_level.sql).
DO $$
DECLARE t TEXT := 'lead_research_interviews';
BEGIN
  IF to_regprocedure('public.audit_stmt()') IS NULL THEN RETURN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'audit_ins_' || t) THEN
    EXECUTE format('CREATE TRIGGER audit_ins_%1$I AFTER INSERT ON %1$I REFERENCING NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION audit_stmt()', t);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'audit_upd_' || t) THEN
    EXECUTE format('CREATE TRIGGER audit_upd_%1$I AFTER UPDATE ON %1$I REFERENCING OLD TABLE AS old_rows NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION audit_stmt()', t);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'audit_del_' || t) THEN
    EXECUTE format('CREATE TRIGGER audit_del_%1$I AFTER DELETE ON %1$I REFERENCING OLD TABLE AS old_rows FOR EACH STATEMENT EXECUTE FUNCTION audit_stmt()', t);
  END IF;
END $$;

COMMIT;
NOTIFY pgrst, 'reload schema';
