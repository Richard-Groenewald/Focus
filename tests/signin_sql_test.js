// Runs sql/add_signin_guard.sql against a real Postgres (PGlite, Postgres compiled to WASM, in
// this process) over a cut-down copy of the tables it touches, and checks what it promises:
// the move, the marker, the refusal of anything without the proxy's internal mark, each auth_*
// function, the privileges, and that a second run changes nothing.
//   npm install --no-save @electric-sql/pglite     (not a project dependency)
//   node tests/signin_sql_test.js
const assert = require('assert');
const fs = require('fs');
const path = require('path');
let PGlite;
try { ({ PGlite } = require('@electric-sql/pglite')); }
catch (e) { console.error('This test needs PGlite:  npm install --no-save @electric-sql/pglite'); process.exit(2); }

const FILE = fs.readFileSync(path.join(__dirname, '..', 'sql', 'add_signin_guard.sql'), 'utf8');

// What the script finds on a Focus database before it runs (columns as on DEV, 22 Nov 2026).
const BEFORE = `
create role service_role; create role anon; create role authenticated;
create table system_users (
  id bigint generated by default as identity primary key, person_id bigint unique, username text not null unique,
  password text not null default '', active boolean default true, created_at timestamptz default now(),
  password_hash text, password_salt text, password_set_at timestamptz,
  must_set_password boolean not null default false, failed_login_count integer not null default 0,
  locked_until timestamptz, session_version integer not null default 1);
create table user_sessions (
  id bigserial primary key, system_user_id bigint, person_id bigint,
  outcome text check (outcome = any (array['ok','failed','locked','resumed'])),
  started_at timestamptz default now(), user_agent text, ip text);
create table audit_log (
  id bigserial primary key, at timestamptz not null default now(), actor_id bigint, table_name text not null,
  row_id bigint, op text not null check (op = any (array['INSERT','UPDATE','DELETE'])), changes jsonb, row_data jsonb, real_actor_id bigint);
grant usage on schema public to service_role, anon, authenticated;
grant all on all tables in schema public to service_role;
-- sql/add_session_version.sql, as installed today
create function bump_session_version() returns trigger language plpgsql set search_path = pg_catalog, public as $$
begin
  if (old.active is not false and new.active is false)
     or new.password_hash is distinct from old.password_hash
     or (old.must_set_password is not true and new.must_set_password is true) then
    new.session_version := coalesce(old.session_version, 1) + 1;
  end if;
  return new;
end; $$;
create trigger system_users_bump_session_version before update on system_users for each row execute function bump_session_version();
insert into system_users (id, person_id, username, password_hash, password_salt, password_set_at, session_version) values
  (4, 1, 'Richard', 'hash-richard', 'salt-richard', now() - interval '30 days', 3),
  (5, 2, 'les',     'hash-les',     'salt-les',     now() - interval '10 days', 1),
  (6, 3, 'newbie',  null,           null,           null,                      1);
update system_users set must_set_password = true where id = 6;
update system_users set session_version = 1 where id = 6;
`;

let db, pass = 0, fail = 0;
const q = async (sql, params) => (await db.query(sql, params)).rows;
const one = async (sql, params) => { const r = await q(sql, params); return r[0] ? Object.values(r[0])[0] : undefined; };
const HEAD = { internal: '{"x-focus-internal":"auth","x-actor-id":"5"}', client: '{"x-focus-client":"1","x-actor-id":"5"}',
  both: '{"x-focus-internal":"auth","x-focus-client":"1"}', bare: '{"x-actor-id":"5"}', junk: 'not json' };
// One statement as a REST request would run it: the headers are transaction-local, as PostgREST sets them.
async function asRequest(headers, sql, params) {
  return db.transaction(async tx => {
    await tx.query(`select set_config('request.headers', $1, true)`, [headers]);
    return (await tx.query(sql, params)).rows;
  });
}
const refused = async (fn) => { try { await fn(); return false; } catch (e) { return String(e.message); } };
const t = async (name, fn) => {
  try { await fn(); pass++; console.log('  ok  ' + name); }
  catch (e) { fail++; console.log('FAIL  ' + name + '\n      ' + String(e && e.message || e).split('\n')[0]); }
};

(async () => {
  db = new PGlite();
  await db.exec(BEFORE);

  await t('the file avoids the word the migration tool stalls on', async () => assert.ok(!/\bdrop\b/i.test(FILE)));
  await t('it runs', async () => { await db.exec(FILE); });

  await t('the move: hashes in focus_auth, the marker on system_users, nobody signed out', async () => {
    const creds = await q('select system_user_id, password_hash, password_salt from focus_auth.credentials order by 1');
    assert.deepStrictEqual(creds, [{ system_user_id: 4, password_hash: 'hash-richard', password_salt: 'salt-richard' },
      { system_user_id: 5, password_hash: 'hash-les', password_salt: 'salt-les' }]);
    const users = await q('select id, password_hash, password_salt, session_version from system_users order by id');
    assert.ok(users.every(u => u.password_hash === '!vault' && u.password_salt === '!vault'));
    assert.deepStrictEqual(users.map(u => u.session_version), [3, 1, 1]);
    assert.ok(await one(`select password_set_at is not null from focus_auth.credentials where system_user_id = 4`));
  });

  await t('a second run changes nothing', async () => {
    const snap = async () => JSON.stringify([await q('select * from focus_auth.credentials order by 1'), await q('select * from focus_auth.config order by 1'),
      await q('select id, password_hash, session_version, must_set_password from system_users order by 1'),
      await q(`select tgname from pg_trigger where tgrelid = 'public.system_users'::regclass and not tgisinternal order by 1`),
      await q(`select conname from pg_constraint where conrelid in ('focus_auth.credentials'::regclass, 'focus_auth.trusted_devices'::regclass) order by 1`)]);
    const before = await snap();
    await db.exec(FILE);
    assert.strictEqual(await snap(), before);
  });

  await t('the marker holds whatever is written to the old columns', async () => {
    await db.exec(`update system_users set password_hash = null, password_salt = null where id = 5`);
    await db.exec(`update system_users set password_hash = 'planted', password_salt = 'planted' where id = 5`);
    await db.exec(`insert into system_users (id, person_id, username) values (7, 4, 'fresh')`);
    await db.exec(`insert into system_users (id, person_id, username, password_hash, password_salt) values (8, 5, 'sneaky', 'h', 's')`);
    assert.deepStrictEqual((await q(`select distinct password_hash, password_salt from system_users`)), [{ password_hash: '!vault', password_salt: '!vault' }]);
    assert.strictEqual(await one('select session_version from system_users where id = 5'), 1, 'and writing to them signs nobody out');
  });

  await t('the session version still moves on deactivation and a forced reset, and on nothing else', async () => {
    await db.exec(`update system_users set username = 'lesley' where id = 5`);
    assert.strictEqual(await one('select session_version from system_users where id = 5'), 1);
    await db.exec(`update system_users set must_set_password = true where id = 5`);
    assert.strictEqual(await one('select session_version from system_users where id = 5'), 2);
    await db.exec(`update system_users set active = false where id = 5`);
    assert.strictEqual(await one('select session_version from system_users where id = 5'), 3);
    await db.exec(`update system_users set active = true, must_set_password = false, username = 'les' where id = 5`);
    assert.strictEqual(await one('select session_version from system_users where id = 5'), 3);
  });

  await t('only a request with the internal mark, and without the client mark, gets in', async () => {
    const fns = [`select auth_read('richard', null)`, `select auth_read(null, 4)`, `select auth_write(4, '{"failed_login_count":0}')`,
      `select auth_totp_step(4, 1)`, `select auth_device_add(4, 'h', now() + interval '1 day', 'ua')`, `select auth_device_ok(4, 'h')`,
      `select auth_admin_list()`, `select auth_config_get()`, `select auth_config_set('trust_days', '30', 1)`, `select auth_audit(1, 4, 'x', 'a', 'b')`];
    for (const sql of fns) {
      for (const k of ['client', 'both', 'bare', 'junk']) {
        const r = await refused(() => asRequest(HEAD[k], sql));
        assert.ok(r && /not allowed/.test(r), sql + ' with ' + k + ' headers → ' + r);
      }
      assert.strictEqual(await refused(() => asRequest(HEAD.internal, sql)), false, sql + ' with the internal mark');
    }
    assert.ok((await q(`select auth_read(null, 4) as r`))[0].r, 'direct SQL by the owner (no request headers) is allowed');
    await db.exec(`delete from focus_auth.trusted_devices; update focus_auth.credentials set totp_last_step = null; delete from audit_log`);
  });

  await t('privileges: service_role may call the functions and nothing else; anon may call nothing', async () => {
    const as = (role, sql) => db.transaction(async tx => { await tx.query('set local role ' + role); return (await tx.query(sql)).rows; });
    assert.ok((await as('service_role', `select auth_read(null, 4) as r`))[0].r);
    for (const sql of ['select * from focus_auth.credentials', 'select * from focus_auth.config', 'select * from focus_auth.trusted_devices', `select focus_auth.cfg('x', 'y')`, 'select focus_auth.guard()']) {
      const r = await refused(() => as('service_role', sql));
      assert.ok(r && /permission denied/.test(r), 'service_role: ' + sql + ' → ' + r);
    }
    for (const role of ['anon', 'authenticated']) {
      for (const sql of [`select auth_read(null, 4)`, `select auth_admin_list()`, `select auth_write(4, '{}')`, `select auth_config_set('trust_days', '1', 1)`]) {
        const r = await refused(() => as(role, sql));
        assert.ok(r && /permission denied/.test(r), role + ': ' + sql + ' → ' + r);
      }
    }
  });

  await t('auth_read: by name in any case, by id, the secrets and the policy', async () => {
    const r = (await q(`select auth_read('  RICHARD ', null) as r`))[0].r;
    assert.deepStrictEqual([r.id, r.person_id, r.username, r.active, r.session_version, r.password_hash, r.password_salt, r.code_required, r.trust_days],
      [4, 1, 'Richard', true, 3, 'hash-richard', 'salt-richard', false, 30]);
    assert.strictEqual((await q(`select auth_read(null, 6) as r`))[0].r.password_hash, null);
    assert.strictEqual((await q(`select auth_read('nobody', null) as r`))[0].r, null);
    assert.strictEqual((await q(`select auth_read(null, null) as r`))[0].r, null);
    assert.strictEqual((await q(`select auth_read('rich%', null) as r`))[0].r, null, 'no wildcards');
  });

  await t('auth_write: only the keys in the patch change', async () => {
    let r = (await q(`select auth_write(4, '{"failed_login_count":3}') as r`))[0].r;
    assert.deepStrictEqual([r.failed_login_count, r.session_version, r.password_hash, r.must_set_password], [3, 3, 'hash-richard', false]);
    r = (await q(`select auth_write(4, '{"failed_login_count":0,"locked_until":"2030-01-01T00:00:00Z"}') as r`))[0].r;
    assert.ok(r.failed_login_count === 0 && /^2030-01-01/.test(r.locked_until));
    r = (await q(`select auth_write(4, '{"locked_until":null}') as r`))[0].r;
    assert.strictEqual(r.locked_until, null);
    r = (await q(`select auth_write(4, '{"password_hash":"h2","password_salt":"s2","must_set_password":false,"bump":true}') as r`))[0].r;
    assert.deepStrictEqual([r.password_hash, r.password_salt, r.session_version], ['h2', 's2', 4]);
    assert.strictEqual(await one(`select password_hash from system_users where id = 4`), '!vault');
    assert.ok(await one(`select password_set_at > now() - interval '1 minute' from system_users where id = 4`));
    // A one-time password: forced reset and the bump together move the version once.
    r = (await q(`select auth_write(4, '{"password_hash":"h3","password_salt":"s3","temp_expires_at":"2030-01-08T00:00:00Z","must_set_password":true,"bump":true}') as r`))[0].r;
    assert.deepStrictEqual([r.must_set_password, r.session_version, /^2030-01-08/.test(r.temp_expires_at)], [true, 5, true]);
    r = (await q(`select auth_write(4, '{"totp_secret":"v1.a.b","totp_confirmed_at":null,"totp_last_step":null}') as r`))[0].r;
    assert.deepStrictEqual([r.totp_secret, r.totp_confirmed_at, r.password_hash], ['v1.a.b', null, 'h3']);
    r = (await q(`select auth_write(4, '{"totp_confirmed_at":"2026-11-22T10:00:00Z","totp_last_step":59000000}') as r`))[0].r;
    assert.ok(r.totp_confirmed_at && +r.totp_last_step === 59000000 && r.totp_secret === 'v1.a.b');
    r = (await q(`select auth_write(6, '{"totp_secret":"v1.c.d"}') as r`))[0].r;
    assert.strictEqual(r.totp_secret, 'v1.c.d', 'a login with no credentials row gets one');
    assert.strictEqual((await q(`select auth_write(999, '{"bump":true}') as r`))[0].r, null);
    assert.strictEqual((await q(`select auth_write(4, null) as r`))[0].r, null);
  });

  await t('a code step is claimed once', async () => {
    const step = async (n) => one(`select auth_totp_step(4, $1)`, [n]);
    assert.strictEqual(await step(59000000), false, 'the step taken at enrolment');
    assert.strictEqual(await step(59000001), true);
    assert.strictEqual(await step(59000001), false);
    assert.strictEqual(await step(59000000), false);
    assert.strictEqual(await step(59000002), true);
    assert.strictEqual(await one(`select auth_totp_step(999, 1)`), false);
  });

  await t('trusted devices: mine, unexpired, ten at most, forgotten on request', async () => {
    await q(`select auth_device_add(4, 'tok-a', now() + interval '30 days', 'ua')`);
    assert.strictEqual(await one(`select auth_device_ok(4, 'tok-a')`), true);
    assert.strictEqual(await one(`select auth_device_ok(5, 'tok-a')`), false);
    assert.strictEqual(await one(`select auth_device_ok(4, 'tok-x')`), false);
    await db.exec(`insert into focus_auth.trusted_devices (system_user_id, token_hash, expires_at) values (4, 'tok-old', now() - interval '1 day')`);
    assert.strictEqual(await one(`select auth_device_ok(4, 'tok-old')`), false);
    for (let i = 0; i < 12; i++) await q(`select auth_device_add(4, $1, now() + interval '30 days', 'ua')`, ['tok-' + i]);
    assert.strictEqual(await one(`select count(*)::int from focus_auth.trusted_devices where system_user_id = 4`), 10);
    assert.strictEqual(await one(`select auth_device_ok(4, 'tok-11')`), true);
    assert.strictEqual(await one(`select auth_device_ok(4, 'tok-a')`), false, 'the oldest went');
    await q(`select auth_device_add(5, 'tok-les', now() + interval '30 days', 'ua')`);
    await q(`select auth_write(4, '{"clear_devices":true}')`);
    assert.deepStrictEqual(await q(`select system_user_id from focus_auth.trusted_devices`), [{ system_user_id: 5 }]);
  });

  await t('the admin list shows state and no secrets', async () => {
    const list = (await q(`select auth_admin_list() as r`))[0].r;
    const by = Object.fromEntries(list.map(u => [u.id, u]));
    assert.deepStrictEqual([by[4].has_password, by[4].must_set_password, !!by[4].enrolled_at, by[4].devices], [true, true, true, 0]);
    assert.deepStrictEqual([by[5].has_password, by[5].enrolled_at, by[5].devices], [true, null, 1]);
    assert.deepStrictEqual([by[6].has_password, by[7].has_password], [false, false]);
    assert.ok(!/hash|salt|v1\./.test(JSON.stringify(list)));
  });

  await t('the policy: defaults, a change, the audit line, unknown keys refused', async () => {
    assert.deepStrictEqual((await q(`select auth_config_get() as r`))[0].r, { code_required: 'false', trust_days: '30' });
    const r = (await q(`select auth_config_set('code_required', 'true', 1) as r`))[0].r;
    assert.strictEqual(r.code_required, 'true');
    await q(`select auth_config_set('code_required', 'true', 1)`);
    const audit = await q(`select actor_id, table_name, op, changes from audit_log where table_name = 'settings'`);
    assert.deepStrictEqual(audit, [{ actor_id: 1, table_name: 'settings', op: 'UPDATE', changes: { signin_code_required: { o: 'false', n: 'true' } } }]);
    assert.strictEqual((await q(`select auth_read(null, 5) as r`))[0].r.code_required, true);
    await q(`select auth_config_set('trust_days', '9999', 1)`);
    assert.strictEqual((await q(`select auth_read(null, 5) as r`))[0].r.trust_days, 365, 'held inside 0 to 365');
    await q(`select auth_config_set('trust_days', 'abc', 1)`);
    assert.strictEqual((await q(`select auth_read(null, 5) as r`))[0].r.trust_days, 30, 'a bad value reads as the default');
    assert.ok(/unknown setting/.test(await refused(() => q(`select auth_config_set('anything', 'x', 1)`))));
    await q(`select auth_audit(1, 5, 'authenticator', 'enrolled', 'reset')`);
    assert.deepStrictEqual(await one(`select changes from audit_log where row_id = 5`), { authenticator: { o: 'enrolled', n: 'reset' } });
  });

  await t('removing a login removes its secrets', async () => {
    await db.exec(`delete from system_users where id = 5`);
    assert.strictEqual(await one(`select count(*)::int from focus_auth.credentials where system_user_id = 5`), 0);
    assert.strictEqual(await one(`select count(*)::int from focus_auth.trusted_devices where system_user_id = 5`), 0);
  });

  await t('after a clone has recreated schema public, a re-run restores the links', async () => {
    const names = await q(`select conname, conrelid::regclass::text as tbl from pg_constraint where contype = 'f' and connamespace = 'focus_auth'::regnamespace`);
    assert.strictEqual(names.length, 2);
    for (const c of names) await db.query(`alter table ${c.tbl} drop constraint ${c.conname}`);
    await db.exec(`insert into focus_auth.credentials (system_user_id, password_hash) values (4242, 'orphan')`);
    await db.exec(FILE);
    assert.strictEqual(await one(`select count(*)::int from pg_constraint where contype = 'f' and connamespace = 'focus_auth'::regnamespace`), 2);
    assert.strictEqual(await one(`select count(*)::int from focus_auth.credentials where system_user_id = 4242`), 0);
    assert.strictEqual((await q(`select auth_read(null, 4) as r`))[0].r.password_hash, 'h3', 'credentials already moved are left alone');
  });

  console.log(`\n${pass}/${pass + fail} passed`);
  process.exit(fail ? 1 : 0);
})().catch(e => { console.error('crashed:', e); process.exit(2); });
